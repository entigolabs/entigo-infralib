#!/bin/bash
# Mirrors the Crossplane provider packages of one crossplane-* module and pins
# them by sha256 digest. Sourced by the module's pullpush.sh, which sets:
#
#   VERSION    package version, the same one templates/provider.yaml renders
#   REGISTRY   upstream registry and organisation, e.g. xpkg.upbound.io/upbound
#   PROVIDERS  space separated package names
#
# Commands (first argument of pullpush.sh):
#
#   digests  Resolve the upstream digest of every package and write the
#            module's values-images.yaml. Needs no credentials. Run it whenever
#            VERSION or PROVIDERS change and commit the result.
#   mirror   (default) Copy every package to the mirrors, by the digest recorded
#            in values-images.yaml, and verify that each mirror serves exactly
#            that digest. Needs a login to the mirrors.
#
# MIRRORS (space separated, default docker.io/entigolabs) lists the mirror
# repository prefixes. A package is copied byte for byte, so its digest is
# the same upstream and on every mirror.
set -uo pipefail
# One sort order everywhere, so the generated file does not depend on the machine.
export LC_ALL=C

MODULE_DIR="$(cd "$(dirname "${BASH_SOURCE[1]}")" && pwd -P)"
VALUES_FILE="$MODULE_DIR/values-images.yaml"
MIRRORS="${MIRRORS:-docker.io/entigolabs}"
COMMAND="${1:-mirror}"

# Digest of an image reference, empty when it does not exist.
digest_of() {
    docker buildx imagetools inspect "$1" --format '{{.Manifest.Digest}}' 2>/dev/null | grep -E '^sha256:[0-9a-f]{64}$'
}

# Digest values-images.yaml records for a package, empty when it has none.
recorded_digest() {
    [ -f "$VALUES_FILE" ] || return 0
    awk -v key="$1:$VERSION:" '$1 == key { print $2 }' "$VALUES_FILE"
}

write_digests() {
    local tmp provider digest failed=0
    tmp=$(mktemp)
    export -f digest_of
    # shellcheck disable=SC2086
    printf '%s\n' $PROVIDERS | sort | xargs -P 8 -I{} bash -c \
        'd=$(digest_of "$0/{}:$1") || d=""; echo "{} $d"' "$REGISTRY" "$VERSION" | sort > "$tmp"
    {
        echo "# Generated by pullpush.sh digests, do not edit by hand."
        echo "#"
        echo "# sha256 digest of every $REGISTRY package this module can install, keyed by"
        echo "# <package>:<version>. templates/provider.yaml appends the digest to a package"
        echo "# reference whose key is listed here, a package without a key is installed by tag."
        echo "imageDigests:"
        while read -r provider digest; do
            if [ -z "$digest" ]; then
                echo "No digest found for $REGISTRY/$provider:$VERSION" >&2
                failed=1
                continue
            fi
            echo "  $provider:$VERSION: $digest"
        done < "$tmp"
    } > "$VALUES_FILE.tmp"
    rm -f "$tmp"
    if [ "$failed" -ne 0 ]; then
        rm -f "$VALUES_FILE.tmp"
        exit 2
    fi
    mv "$VALUES_FILE.tmp" "$VALUES_FILE"
    echo "Wrote $(grep -c sha256: "$VALUES_FILE") digests to $VALUES_FILE"
    # The file was written anew: put the module's pod image digests back.
    if [ -f "$MODULE_DIR/pod-images.txt" ]; then
        "$(dirname "${BASH_SOURCE[0]}")/pod-images.sh" "$MODULE_DIR" || exit 2
    fi
}

mirror() {
    local provider digest mirror dest found
    for provider in $PROVIDERS; do
        digest=$(recorded_digest "$provider")
        if [ -z "$digest" ]; then
            echo "$provider:$VERSION has no digest in $VALUES_FILE, run '$0 digests' and commit the result" >&2
            exit 2
        fi
        for mirror in $MIRRORS; do
            dest="$mirror/$provider:$VERSION"
            found=$(digest_of "$dest")
            if [ -z "$found" ]; then
                echo "Copying $REGISTRY/$provider@$digest to $dest"
                if ! docker buildx imagetools create --tag "$dest" "$REGISTRY/$provider@$digest"; then
                    echo "Failed to copy $REGISTRY/$provider@$digest to $dest" >&2
                    exit 2
                fi
                found=$(digest_of "$dest")
            else
                echo "Skipping $provider - already exists at $dest"
            fi
            if [ "$found" != "$digest" ]; then
                echo "$dest is $found, values-images.yaml records $digest" >&2
                exit 2
            fi
        done
    done
    echo "All providers copied successfully"
}

case "$COMMAND" in
    digests) write_digests ;;
    mirror) mirror ;;
    *) echo "Usage: $0 [mirror|digests]" >&2; exit 1 ;;
esac
