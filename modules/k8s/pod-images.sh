#!/bin/bash
# Pins pod images of k8s modules by sha256 digest.
#
#   pod-images.sh modules/k8s/argocd modules/k8s/harbor ...
#
# A module lists the images to pin in its pod-images.txt, one per line:
#
#   <value path of the tag> <image repository>
#   job.tag docker.io/entigolabs/entigo-infralib-kubectl
#
# For every line the tag is read from the module's values.yaml, its digest is
# resolved in the registry and "<tag>@<digest>" is written to the same value
# path in the module's values-images.yaml. Needs docker and yq, no credentials.
# Run it whenever a listed tag changes and commit the result; the static check
# fails while values-images.yaml still carries the previous tag.
#
# The imageDigests of a crossplane-* module (pullpush.sh digests) are kept,
# every other value of the file is replaced by what the list says.
set -euo pipefail

[ $# -gt 0 ] || { sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 1; }

for module in "$@"; do
    module=${module%/}
    list="$module/pod-images.txt"
    out="$module/values-images.yaml"
    [ -f "$list" ] || { echo "$list not found" >&2; exit 2; }
    tmp=$(mktemp)
    if [ -s "$out" ]; then
        yq 'with_entries(select(.key == "imageDigests"))' "$out" > "$tmp"
    fi
    # A file with nothing left in it gets its header again.
    grep -q '^[^#]' "$tmp" && ! grep -qx '{}' "$tmp" || echo "# Generated by pod-images.sh from pod-images.txt, do not edit by hand." > "$tmp"
    count=0
    while read -r path image _; do
        case "$path" in ''|'#'*) continue ;; esac
        tag=$(yq ".$path // \"\"" "$module/values.yaml")
        [ -n "$tag" ] || { echo "$module/values.yaml has no $path" >&2; exit 2; }
        digest=$(docker buildx imagetools inspect "$image:$tag" --format '{{.Manifest.Digest}}' 2>/dev/null | grep -E '^sha256:[0-9a-f]{64}$') \
            || { echo "No digest found for $image:$tag" >&2; exit 2; }
        v="$tag@$digest" yq -i ".$path = strenv(v)" "$tmp"
        count=$((count + 1))
    done < "$list"
    # Not mv: the file keeps its mode, mktemp's is private.
    cat "$tmp" > "$out"
    rm -f "$tmp"
    echo "Wrote $count image digests to $out"
done
